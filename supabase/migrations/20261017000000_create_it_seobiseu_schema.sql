-- Políticas de lectura y escritura para permitir acceso a la aplicación y usuarios autorizados
DO $$
DECLARE
    tbl text;
    tables text[] := ARRAY[
        'roles', 'usuarios', 'clientes', 'sedes', 'sla',
        'tickets', 'ordenes_trabajo', 'inventario',
        'movimientos_inventario', 'bitacora_tickets'
    ];
BEGIN
    FOREACH tbl IN ARRAY tables LOOP
        EXECUTE format('DROP POLICY IF EXISTS "allow_all_for_service_and_app" ON public.%I;', tbl);
        EXECUTE format('CREATE POLICY "allow_all_for_service_and_app" ON public.%I FOR ALL USING (true) WITH CHECK (true);', tbl);
    END LOOP;
END $$;

